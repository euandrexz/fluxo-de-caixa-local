const assert = require('node:assert/strict');
const {readFileSync} = require('node:fs');
const {join} = require('node:path');
const {cents, date, statement, newRows, balance, totals, readStatement, reconcile, keyword, suggestions, undoImport, upgrade, backup, restore} = require('../src/core.js');

assert.equal(cents('R$ 1.234,56'),123456);
assert.equal(cents('-25.15'),-2515);
assert.equal(cents('0,29'),29);
assert.equal(date('31/02/2026'),'');
const imported = statement('\uFEFFData;Descrição;Valor;Pessoa\r\n25/11/2026;"Venda; chip";25,00;Cliente\r\n26/11/2026;Pix BM;-120,50;Fornecedor BM');
assert.equal(imported[0].description,'Venda; chip');
assert.equal(imported[1].amount,-12050);
assert.equal(imported[1].person,'Fornecedor BM');
assert.deepEqual(statement('Data;Descrição;Entrada;Saída\n26/11/2026;Pix;;12,45').map(row => row.amount),[-1245]);
assert.throws(() => statement('Data;Descrição;Valor\n31/02/2026;Pix;25,00'),/inválido/);
const ofx = '<OFX><CURDEF>BRL\n<STMTTRN><DTPOSTED>20261126093000.000[-3:BRT]\n<TRNAMT>-41.05\n<FITID>AA\n<NAME>BM &amp; Cia\n<MEMO>Compra\n</STMTTRN></OFX>';
const [transaction] = statement(ofx);
assert.equal(transaction.description,'BM & Cia · Compra');
assert.equal(transaction.amount,-4105);
assert.equal(transaction.date,'2026-11-26');
assert.equal(newRows([transaction,transaction],[],'bank').length,1);
const existing = [{...imported[0],accountId:'bank',amount:999,description:'Atualizado',original:imported[0]}];
assert.deepEqual(newRows([imported[0],imported[0],imported[1]],existing,'bank'),imported);
assert.equal(newRows(imported,existing,'other').length,2);
assert.equal(balance({id:'bank',opening:100000,baseDate:'2026-11-25'},imported.map(row => ({...row,accountId:'bank'})),'2026-11-26'),87950);
assert.deepEqual(totals([imported[0],{...imported[1],internal:true}]),{income:2500,expense:0});
const parsed = readStatement(readFileSync(join(__dirname,'fixtures/fechamento-teste.ofx'),'utf8'));
assert.deepEqual(parsed.closing,{date:'2026-11-26',amount:11000});
assert.equal(readStatement('<OFX><LEDGERBAL><BALAMT>0.00<DTASOF>20261126</LEDGERBAL></OFX>').rows.length,0);
assert.throws(() => readStatement('<OFX><STMTRS></STMTRS><CCSTMTRS></CCSTMTRS></OFX>'),/mais de um/);
const account = {id:'bank',name:'Conta de teste',bank:'Banco fictício',opening:10000,baseDate:'2026-11-24'};
const batch = {id:'import',accountId:'bank',file:'fechamento-teste.ofx',at:'2026-11-26T12:00:00Z',count:2,closing:parsed.closing,undoneAt:null};
const mapped = parsed.rows.map(({date,description,amount,external,person}) => ({id:external,accountId:'bank',importId:batch.id,
  date,description,amount,external,person,tags:[],reason:'',internal:false,original:{date,description,amount}}));
assert.deepEqual(reconcile(account,mapped,parsed.closing),{calculated:11000,difference:0});
assert.deepEqual(reconcile(account,[],parsed.closing),{calculated:10000,difference:-1000});
assert.equal(reconcile({...account,baseDate:'2026-11-27'},mapped,parsed.closing),null);
const keywords = [{id:'word',term:'Fornecedor BM',tag:'Estoque'}];
assert.equal(keyword('  Fornecédor-BM  '),'fornecedor bm');
assert.deepEqual(suggestions(keywords,mapped[1]),['Estoque']);
assert.deepEqual(suggestions(keywords,{description:'Fornecedor BMS'}),[]);
const added = {id:'manual',accountId:'bank',date:'2026-11-25',description:'Outro recebimento',amount:900,person:'',reason:'',tags:[],internal:false};
const data = upgrade({accounts:[account],tags:['Estoque'],keywords,rows:[...mapped,added],imports:[batch]});
const restored = restore(JSON.stringify(backup(data)));
assert.deepEqual(restored,data);
assert.deepEqual(restore(JSON.stringify({...backup(data),app:'quem-levou-meu-saldo'})),data);
assert.throws(() => restore('{}'),/compatível/);
assert.throws(() => restore('{'),/JSON válido/);
assert.throws(() => restore(JSON.stringify(backup({...data,accounts:[]}))),/inválidos/);
assert.deepEqual(upgrade({rows:[added]}).imports,[]);
const undone = undoImport(restored,'import','2026-11-26T13:00:00Z');
assert.deepEqual(undone.rows,[added]);
assert.deepEqual(undone.imports.map(item => item.undoneAt),['2026-11-26T13:00:00Z']);
assert.deepEqual(restore(JSON.stringify(backup(undone))),undone);
assert.throws(() => undoImport(undone,'import','2026-11-26T13:00:00Z'),/já foi desfeita/);
assert.equal(newRows(parsed.rows,undone.rows,'bank').length,2);
console.log('Validação de extratos, saldos, sugestões, reversão e backup concluída.');
